export function getAuthenticSaudiBookPage(
  bookTitle: string,
  subject: string,
  grade: string,
  pageNumber: number,
  lessonTitleHint?: string
): BookPageAnalysisResult {
  const p = Math.max(1, pageNumber);
  const cleanSubject = (subject || '').trim();
  const cleanBookTitle = (bookTitle || '').trim();

  // Normalize subject categories
  const isIslamic =
    cleanSubject.includes('إسلام') ||
    cleanSubject.includes('دين') ||
    cleanSubject.includes('توحيد') ||
    cleanSubject.includes('فقه') ||
    cleanSubject.includes('تفسير') ||
    cleanSubject.includes('حديث') ||
    cleanBookTitle.includes('الإسلامية');

  const isMath =
    cleanSubject.includes('رياضيات') ||
    cleanSubject.includes('جبر') ||
    cleanSubject.includes('هندسة') ||
    cleanBookTitle.includes('الرياضيات');

  const isScience =
    cleanSubject.includes('علوم') ||
    cleanSubject.includes('فيزياء') ||
    cleanSubject.includes('كيمياء') ||
    cleanSubject.includes('أحياء') ||
    cleanBookTitle.includes('العلوم') ||
    cleanBookTitle.includes('الفيزياء') ||
    cleanBookTitle.includes('الكيمياء') ||
    cleanBookTitle.includes('الأحياء');

  const isArabic =
    cleanSubject.includes('عربي') ||
    cleanSubject.includes('لغتي') ||
    cleanSubject.includes('كفايات') ||
    cleanBookTitle.includes('لغتي') ||
    cleanBookTitle.includes('الكفايات');

  const isSocial =
    cleanSubject.includes('اجتماع') ||
    cleanSubject.includes('تاريخ') ||
    cleanSubject.includes('جغرافي') ||
    cleanBookTitle.includes('الاجتماعية');

  const isDigital =
    cleanSubject.includes('رقمية') ||
    cleanSubject.includes('حاسب') ||
    cleanSubject.includes('برمج') ||
    cleanSubject.includes('ذكاء') ||
    cleanBookTitle.includes('الرقمية') ||
    cleanBookTitle.includes('الحاسب');

  const isEnglish =
    cleanSubject.toLowerCase().includes('english') ||
    cleanBookTitle.toLowerCase().includes('english') ||
    cleanBookTitle.toLowerCase().includes('goal') ||
    cleanBookTitle.toLowerCase().includes('we can');

  // ============================================================================
  // SPECIALIZED ENGINE: التجويد (مدارس تحفيظ القرآن الكريم والتعليم العام)
  // ============================================================================
  if (cleanSubject.includes('تجويد') || cleanBookTitle.includes('التجويد')) {
    return getTajweedM1TahfeezPageData(p);
  }

  // ============================================================================
  // 1. INTRODUCTORY & PREFATORY PAGES (الصفحات التمهيدية الأولى ص 1 إلى ص 9)
  // ============================================================================
  if (p <= 9) {
    return getIntroductoryPageData(cleanBookTitle, cleanSubject, grade, p);
  }

  // ============================================================================
  // 2. ISLAMIC STUDIES (الدراسات الإسلامية - التوحيد والتفسير والحديث والفقه)
  // ============================================================================
  if (isIslamic) {
    return getIslamicStudiesPageData(cleanBookTitle, cleanSubject, grade, p, lessonTitleHint);
  }

  // ============================================================================
  // 3. MATHEMATICS (الرياضيات)
  // ============================================================================
  if (isMath) {
    return getMathematicsPageData(cleanBookTitle, cleanSubject, grade, p, lessonTitleHint);
  }

  // ============================================================================
  // 4. SCIENCE (العلوم والفيزياء والكيمياء والأحياء)
  // ============================================================================
  if (isScience) {
    return getSciencePageData(cleanBookTitle, cleanSubject, grade, p, lessonTitleHint);
  }

  // ============================================================================
  // 5. ARABIC LANGUAGE (لغتي الجميلة / لغتي الخالدة / الكفايات اللغوية)
  // ============================================================================
  if (isArabic) {
    return getArabicLanguagePageData(cleanBookTitle, cleanSubject, grade, p, lessonTitleHint);
  }

  // ============================================================================
  // 6. SOCIAL STUDIES & NATIONAL IDENTITY (الدراسات الاجتماعية والوطنية)
  // ============================================================================
  if (isSocial) {
    return getSocialStudiesPageData(cleanBookTitle, cleanSubject, grade, p, lessonTitleHint);
  }

  // ============================================================================
  // 7. DIGITAL SKILLS & PROGRAMMING (المهارات والتقنية الرقمية)
  // ============================================================================
  if (isDigital) {
    return getDigitalSkillsPageData(cleanBookTitle, cleanSubject, grade, p, lessonTitleHint);
  }

  // ============================================================================
  // 8. GENERAL AUTHENTIC FALLBACK FOR OTHER SUBJECTS (English, Critical Thinking, etc.)
  // ============================================================================
  return getGeneralAuthenticPageData(cleanBookTitle, cleanSubject, grade, p, lessonTitleHint);
}

