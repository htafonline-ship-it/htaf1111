function cleanIsEnglish(title: string, subject: string): boolean {
  const t = (title + ' ' + subject).toLowerCase();
  return t.includes('english') || t.includes('goal') || t.includes('we can') || t.includes('انجليزي') || t.includes('إنجليزية');
}
